import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';
import express from 'express';

const root = fileURLToPath(new URL('../../', import.meta.url));
test('organization services preserve scoped relationships and real lifecycle data', async t => {
  const directory = fs.mkdtempSync(path.join(os.tmpdir(), 'orbit-stage4-org-'));
  const generated = path.join(directory, 'organization.cjs');
  await build({ stdin: { contents: "export { createOrganizationRouter, reportDeadlinePassed } from './server/domain/organization.ts'; export { ScopedState, membership } from './server/policy/scope.ts'; export { SqliteStore, emptyState } from './server/db/store.ts';", resolveDir: root }, outfile: generated, bundle: true, platform: 'node', target: 'node24', format: 'cjs', logLevel: 'silent' });
  const { createOrganizationRouter, reportDeadlinePassed, ScopedState, membership, SqliteStore, emptyState } = createRequire(import.meta.url)(generated);
  const state = emptyState();
  state.users = ['owner', 'reviewer', 'writer', 'viewer', 'outside'].map(id => ({ id, name: id + ' name', username: id, email: id + '@test.invalid', role: id === 'outside' ? 'OWNER' : 'USER', systemRole: id === 'outside' ? 'ADMIN' : 'USER', accountStatus: 'ACTIVE' }));
  state.workspaces = [{ id: 'workspace_a', ownerId: 'owner', members: [{ userId: 'reviewer', role: 'MEMBER', permissions: ['write'] }, { userId: 'writer', role: 'MEMBER', permissions: ['write'] }, { userId: 'viewer', role: 'VIEWER', permissions: ['read'] }] }, { id: 'workspace_b', ownerId: 'outside', members: [] }];
  state.projects = [{ id: 'project_a', workspaceId: 'workspace_a', name: 'A', progress: 0 }, { id: 'project_b', workspaceId: 'workspace_b', name: 'B', progress: 0 }];
  const scoped = new ScopedState(state);
  const dbFile = path.join(directory, 'test.sqlite'); let store = new SqliteStore(dbFile); store.saveState(state);
  const events = [];
  const app = express(); app.use(express.json());
  app.use((req, res, next) => {
    const user = state.users.find(row => row.id === req.headers['x-test-user']); const workspaceId = String(req.headers['x-workspace-id'] || 'workspace_a');
    if (!user || !membership(state, user, workspaceId)) return res.status(403).json({ error: 'FORBIDDEN' });
    req.snapshot = structuredClone(state);
    const send = res.json.bind(res);
    res.json = value => { if (!req.failed && req.method !== 'GET') store.saveState(state); return send(value); };
    scoped.run({ kind: 'workspace', user, workspaceId, method: req.method, path: req.path }, next);
  });
  app.use('/api', createOrganizationRouter({ scoped, broadcast: (event, payload) => events.push({ event, payload }) }));
  app.use((error, req, res, _next) => { req.failed = true; if (req.snapshot) { for (const key of Object.keys(state)) delete state[key]; Object.assign(state, req.snapshot); } res.status(error.status || 500).json({ error: error.code || error.message }); });
  const server = app.listen(0, '127.0.0.1'); await new Promise(resolve => server.once('listening', resolve));
  const base = `http://127.0.0.1:${server.address().port}/api`;
  t.after(async () => { server.closeAllConnections(); await new Promise(resolve => server.close(resolve)); store.close(); fs.rmSync(directory, { recursive: true, force: true }); });
  const call = async (route, body, method = body === undefined ? 'GET' : 'POST', user = 'owner', workspace = 'workspace_a') => { const response = await fetch(base + route, { method, headers: { 'content-type': 'application/json', 'x-test-user': user, 'x-workspace-id': workspace }, ...(body === undefined ? {} : { body: JSON.stringify(body) }) }); return { status: response.status, body: await response.json() }; };
  const ok = (response, status = 200) => { assert.equal(response.status, status, JSON.stringify(response.body)); return response.body; };
  let organization, department, team, definition, instance, content, bug;

  await t.test('empty workspace reads never seed sample organizations, teams or modules', async () => {
    const before = structuredClone(state);
    const data = ok(await call('/org/data'));
    for (const name of ['organizations', 'departments', 'teams', 'moduleDefinitions', 'moduleInstances']) assert.deepEqual(data[name], []);
    assert.deepEqual(state, before);
    assert.equal((await call('/org/departments', { name: 'Unauthorized' }, 'POST', 'writer')).status, 403);
    assert.equal((await call('/org/data', undefined, 'GET', 'outside')).status, 403);
  });
  await t.test('organization, department leaders and unique team members create real channels', async () => {
    organization = ok(await call('/organizations', { name: 'Test organization', slug: 'test' }), 201);
    department = ok(await call('/org/departments', { name: 'Development', organizationId: organization.id, leaderId: 'reviewer', description: '' }), 201);
    assert.equal(state.departmentMembers.find(row => row.departmentId === department.id).userId, 'reviewer');
    team = ok(await call('/org/teams', { name: 'Implementation', departmentId: department.id, leaderId: 'reviewer', memberIds: ['writer', 'reviewer', 'writer'] }), 201);
    assert.equal(team.membersCount, 2);
    assert.equal(state.teamMembers.filter(row => row.teamId === team.id).length, 2);
    const channels = state.conversations.filter(row => row.teamId === team.id);
    assert.equal(channels.length, 4); assert.equal(state.messages.length, 1);
    assert.equal(state.messages[0].kind, 'system'); assert.equal(state.messages[0].system, true);
    assert.equal(state.messages[0].senderId, 'owner');
    assert.equal(state.messages[0].conversationId, channels.find(channel=>channel.channelType==='private_chat').id);
    const leaderChannel = channels.find(row => row.channelType === 'leader_channel');
    assert.deepEqual(state.conversationMembers.filter(row => row.conversationId === leaderChannel.id).map(row => row.userId).sort(), ['owner', 'reviewer']);
    assert.equal((await call('/org/teams', { name: 'Invalid', departmentId: department.id, memberIds: ['outside'] })).status, 422);
    assert.equal((await call('/org/departments', { name: 'Bad parent', organizationId: 'missing' })).status, 404);
    assert.equal(state.teams.length, 1);
    const updated = ok(await call('/org/teams/' + team.id, { description: '', leaderId: 'writer', memberIds: ['writer'] }, 'PUT'));
    assert.equal(updated.membersCount, 1);
    assert.equal(state.messages.length, 1, 'Membership changes do not invent another creation event.');
    assert.deepEqual(state.conversationMembers.filter(row => row.conversationId === leaderChannel.id).map(row => row.userId).sort(), ['owner', 'writer']);
    assert.equal(state.teamMembers.some(row => row.teamId === team.id && row.userId === 'reviewer'), false);
  });
  await t.test('module definitions, instances and atomic records validate schema and preserve concurrent inserts', async () => {
    assert.equal((await call('/org/modules', { name: 'Bad fields', structure: { fields: ['Title', 'Title'] } })).status, 422);
    definition = ok(await call('/org/modules', { name: 'Requests', structure: { fields: ['Title', 'Notes'] } }), 201);
    instance = ok(await call('/org/module-instances', { definitionId: definition.id, departmentId: department.id, name: 'Department requests' }), 201);
    assert.equal(instance.organizationId, organization.id);
    assert.equal(state.departmentModules[0].moduleInstanceId, instance.id);
    const results = await Promise.all([call('/org/module-instances/' + instance.id + '/records', { data: { Title: 'One', Notes: 'A' } }, 'POST', 'writer'), call('/org/module-instances/' + instance.id + '/records', { data: { Title: 'Two', Notes: 'B' } }, 'POST', 'writer')]);
    const records = results.map(result => ok(result, 201).record);
    assert.notEqual(records[0].id, records[1].id); assert.equal(state.moduleInstances[0].config.records.length, 2);
    assert.equal(records[0].creatorId, 'writer'); assert.match(records[0].createdAt, /^\d{4}-\d{2}-\d{2}T/);
    assert.equal((await call('/org/module-instances/' + instance.id + '/records', { data: { Unknown: 'value' } }, 'POST', 'writer')).status, 422);
    assert.equal((await call('/org/module-instances/' + instance.id, { config: { records: [] } }, 'PUT')).status, 409);
    assert.equal((await call('/org/modules/' + definition.id, { structure: { fields: ['Renamed'] } }, 'PUT')).status, 422);
    const edited = ok(await call('/org/module-instances/' + instance.id + '/records/' + records[0].id, { data: { Title: 'Edited', Notes: '' } }, 'PUT', 'writer'));
    assert.equal(edited.record.data.Title, 'Edited'); assert.equal(edited.instance.config.records.length, 2);
    ok(await call('/org/module-instances/' + instance.id + '/records/' + records[1].id, {}, 'DELETE', 'writer'));
    assert.equal(state.moduleInstances[0].config.records.length, 1);
    assert.equal((await call('/org/module-instances/' + instance.id + '/records', { data: { Title: 'No' } }, 'POST', 'viewer')).status, 403);
    assert.equal((await call('/org/module-instances/' + instance.id + '/records', { data: { Title: 'No' } }, 'POST', 'outside', 'workspace_b')).status, 404);
  });
  await t.test('checklists derive progress from status and never fabricate assignees or dates', async () => {
    const item = ok(await call('/wordpress-checklist', { name: 'Security', category: 'security', projectId: 'project_a', ownerId: 'writer' }, 'POST', 'writer'), 201);
    assert.equal(item.owner, 'writer name'); assert.equal(item.dueDate, ''); assert.equal(item.progress, 0);
    const done = ok(await call('/wordpress-checklist/' + item.id, { status: 'completed', progress: 2 }, 'PUT', 'writer')); assert.equal(done.progress, 100);
    const reopened = ok(await call('/wordpress-checklist/' + item.id, { status: 'inprogress' }, 'PUT', 'writer')); assert.equal(reopened.progress, 0);
    assert.equal((await call('/wordpress-checklist/' + item.id, { progress: 101 }, 'PUT', 'writer')).status, 422);
    assert.equal((await call('/seo-checklist', { name: 'SEO', category: 'hosting' }, 'POST', 'writer')).status, 422);
    assert.equal((await call('/seo-checklist', { name: 'Foreign', projectId: 'project_b' }, 'POST', 'writer')).status, 404);
    assert.equal((await call('/seo-checklist', { name: 'Denied' }, 'POST', 'viewer')).status, 403);
    const seo = ok(await call('/seo-checklist', { name: 'Technical SEO', category: 'technical', assignedTo: '', dueDate: '۱۴۰۵/۰۱/۰۱' }, 'POST', 'writer'), 201);
    assert.equal(seo.dueDateCanonical, '2026-03-21'); assert.equal(seo.dueDate, '۱۴۰۵/۰۱/۰۱'); assert.equal(seo.assignedTo, '');
    ok(await call('/seo-checklist/' + seo.id, {}, 'DELETE', 'writer')); assert.equal(state.seoChecklist.length, 0);
  });
  await t.test('content approval uses assigned reviewer identity and invalidates approval after editing', async () => {
    assert.equal((await call('/content-center', { pageName: 'Escalation', reviewerId: 'writer', status: 'approved' }, 'POST', 'writer')).status, 403);
    content = ok(await call('/content-center', { pageName: 'Landing', projectId: 'project_a', writerId: 'writer', reviewerId: 'reviewer', contentBody: 'Draft' }), 201);
    assert.equal(content.writer, 'writer name'); assert.equal(content.reviewer, 'reviewer name');
    ok(await call('/content-center/' + content.id, { status: 'review' }, 'PUT', 'writer'));
    assert.equal((await call('/content-center/' + content.id, { approvalStatus: 'approved', status: 'approved' }, 'PUT', 'writer')).status, 403);
    const approved = ok(await call('/content-center/' + content.id, { status: 'approved', approvalStatus: 'approved' }, 'PUT', 'reviewer')); assert.equal(approved.approvedById, 'reviewer');
    ok(await call('/content-center/' + content.id, { status: 'published' }, 'PUT', 'reviewer'));
    const changed = ok(await call('/content-center/' + content.id, { contentBody: 'New draft' }, 'PUT', 'writer'));
    assert.equal(changed.status, 'writing'); assert.equal(changed.approvalStatus, 'pending'); assert.equal(changed.approvedById, null);
    assert.ok(changed.history.some(row => row.actorId === 'reviewer' && row.kind === 'approval'));
    assert.equal((await call('/content-center/' + content.id, { reviewerId: 'writer' }, 'PUT', 'writer')).status, 403);
    assert.equal((await call('/content-center/' + content.id, { status: 'published' }, 'PUT', 'reviewer')).status, 409);
  });
  await t.test('QA lifecycle requires a fix before verification and tracks reopen history', async () => {
    bug = ok(await call('/qa-bugs', { title: 'Form validation', projectId: 'project_a', category: 'forms', priority: 'HIGH', severity: 'critical', assigneeId: 'writer' }, 'POST', 'writer'), 201);
    assert.equal(bug.priority, 'high'); assert.equal(bug.assignedTo, 'writer name'); assert.equal(bug.fixVersion, '');
    assert.equal((await call('/qa-bugs/' + bug.id, { status: 'verified' }, 'PUT', 'writer')).status, 409);
    ok(await call('/qa-bugs/' + bug.id, { status: 'fixed', fixVersion: '1.2.0' }, 'PUT', 'writer'));
    const verified = ok(await call('/qa-bugs/' + bug.id, { status: 'verified' }, 'PUT', 'reviewer')); assert.equal(verified.verifiedById, 'reviewer');
    const reopened = ok(await call('/qa-bugs/' + bug.id, { status: 'reopened' }, 'PUT', 'reviewer')); assert.equal(reopened.reopenCount, 1); assert.equal(reopened.verifiedAt, null);
    assert.equal(reopened.history.length, 4);
    assert.equal((await call('/qa-bugs/' + bug.id, { severity: 'pretend' }, 'PUT', 'writer')).status, 422);
  });
  await t.test('date-only report deadlines remain open through their local calendar day', () => {
    const at = new Date(2026, 9, 18, 12, 0, 0);
    assert.equal(reportDeadlinePassed('2026-10-18', at), false);
    assert.equal(reportDeadlinePassed('2026-10-17', at), true);
    assert.equal(reportDeadlinePassed('2026-10-19', at), false);
    assert.equal(reportDeadlinePassed(new Date(at.getTime() - 1000).toISOString(), at), true);
    assert.equal(reportDeadlinePassed(new Date(at.getTime() + 1000).toISOString(), at), false);
    assert.equal(reportDeadlinePassed('2026-02-31', at), false);
    assert.equal(reportDeadlinePassed('۱۴۰۵/۰۱/۰۱', at), false);
    assert.equal(reportDeadlinePassed(null, at), false);
  });
  await t.test('department reports include empty assigned projects and exclude cancelled work from overdue and pending', async () => {
    const reportDepartment = ok(await call('/org/departments', { name: 'Report boundary' }), 201);
    const projectIds = ['report_empty_project', 'report_work_project'];
    const taskIds = ['report_late', 'report_cancelled', 'report_today', 'report_complete'];
    state.projects.push({ id: projectIds[0], workspaceId: 'workspace_a', departmentId: reportDepartment.id, status: 'COMPLETED' }, { id: projectIds[1], workspaceId: 'workspace_a', departmentId: reportDepartment.id, status: 'ACTIVE' });
    const at = new Date();
    const today = `${at.getFullYear()}-${String(at.getMonth() + 1).padStart(2, '0')}-${String(at.getDate()).padStart(2, '0')}`;
    state.tasks.push(...taskIds.map((id, index) => ({ id, workspaceId: 'workspace_a', projectId: projectIds[1], departmentId: reportDepartment.id, status: ['pending', 'cancelled', 'pending', 'completed'][index], deadlineCanonical: index === 2 ? today : '2020-01-01' })));
    const report = ok(await call('/org/departments/' + reportDepartment.id + '/reports', {}), 201);
    assert.equal(report.projectSummary.totalProjects, 2);
    assert.equal(report.projectSummary.completedProjects, 1, 'Project completion follows lifecycle status, including an explicitly completed empty project.');
    assert.equal(report.taskSummary.total, 4);
    assert.equal(report.taskSummary.completed, 1);
    assert.equal(report.taskSummary.cancelled, 1);
    assert.equal(report.taskSummary.pending, 2);
    assert.equal(report.metrics.overdue, 1);
    assert.equal(report.metrics.cancelled, 1);
    assert.equal(report.metrics.pending, 2);
    state.tasks = state.tasks.filter(row => !taskIds.includes(row.id));
    state.projects = state.projects.filter(row => !projectIds.includes(row.id));
    ok(await call('/org/departments/' + reportDepartment.id, {}, 'DELETE'));
  });
  await t.test('reports use real deadlines, server metadata and preserve ambiguous legacy dates in bulk filtering', async () => {
    state.tasks.push({ id: 'due', workspaceId: 'workspace_a', projectId: 'project_a', departmentId: department.id, status: 'pending', priority: 'low', deadlineCanonical: '2020-01-01' }, { id: 'future', workspaceId: 'workspace_a', projectId: 'project_a', departmentId: department.id, status: 'pending', priority: 'critical', deadlineCanonical: '2099-01-01' });
    const report = ok(await call('/org/departments/' + department.id + '/reports', {}), 201);
    assert.equal(report.metrics.overdue, 1); assert.equal(report.metrics.efficiency, 0); assert.equal(report.creatorId, 'owner');
    assert.equal((await call('/org/reports', { id: 'forged', title: 'Forged' })).status, 422);
    const manual = ok(await call('/org/reports', { title: 'Manual', departmentId: department.id, content: 'Visible report' }, 'POST', 'writer'), 201);
    state.departmentReports.push({ id: 'legacy_date', workspaceId: 'workspace_a', departmentId: department.id, title: 'Unknown date', generatedAt: '۱۴۰۵/۰۱/۰۱' });
    const deleted = ok(await call('/org/reports/bulk?range=today', {}, 'DELETE'));
    assert.equal(deleted.count, 2); assert.equal(state.departmentReports.some(row => row.id === 'legacy_date'), true);
    assert.equal(state.departmentReports.some(row => row.id === manual.id), false);
    const result = ok(await call('/org/reports/bulk', { ids: ['nonexistent', 'legacy_date'] }, 'DELETE')); assert.equal(result.count, 1);
    const template = ok(await call('/org/templates', { name: 'Reusable schema', structure: { departments: [{ name: 'Design' }] } }), 201);
    assert.equal(template.createdBy, 'owner name'); assert.equal(state.departments.length, 1);
  });
  await t.test('navigation creates only local paths and group deletion removes its items', async () => {
    const group = ok(await call('/org/navigation-groups', { name: { fa: 'عملیات', en: 'Operations' } }), 201);
    assert.equal((await call('/org/navigation-items', { name: { fa: 'خراب', en: '' }, groupId: group.id, path: '//evil.test' })).status, 422);
    ok(await call('/org/navigation-items', { name: { fa: 'درخواست‌ها', en: 'Requests' }, groupId: group.id, moduleId: instance.id, path: '/requests' }), 201);
    assert.equal(state.navigationItems.length, 1);
    ok(await call('/org/navigation-groups/' + group.id, {}, 'DELETE')); assert.equal(state.navigationItems.length, 0);
  });
  await t.test('ambiguous legacy dependencies block destructive cascades without changing data', async () => {
    state.departmentReports.push({ id: 'legacy_conflict', workspaceId: 'workspace_b', departmentId: department.id, title: 'Conflicting workspace' });
    const before = JSON.stringify(state);
    assert.equal((await call('/org/departments/' + department.id, {}, 'DELETE')).status, 409);
    assert.equal(JSON.stringify(state), before);
    state.departmentReports = state.departmentReports.filter(row => row.id !== 'legacy_conflict');
  });
  await t.test('department cascade cleans modules and private channels while preserving work and foreign workspace', async () => {
    const foreign = structuredClone(state.projects.find(row => row.id === 'project_b'));
    state.projects.find(row => row.id === 'project_a').assignedTeamIds = [team.id];
    state.tasks[0].teamId = team.id;
    const taskIds = state.tasks.map(row => row.id);
    ok(await call('/org/departments/' + department.id, {}, 'DELETE'));
    assert.deepEqual(state.tasks.map(row => row.id), taskIds);
    assert.equal(state.tasks[0].departmentId, null); assert.equal(state.tasks[0].teamId, null);
    assert.deepEqual(state.projects.find(row => row.id === 'project_a').assignedTeamIds, []);
    for (const name of ['departments', 'departmentMembers', 'departmentModules', 'moduleInstances', 'teams', 'teamMembers', 'conversations', 'conversationMembers']) assert.equal(state[name].length, 0, name);
    assert.deepEqual(state.projects.find(row => row.id === 'project_b'), foreign);
    assert.equal(state.moduleDefinitions.length, 1);
    assert.equal(store.database.prepare('PRAGMA foreign_key_check').all().length, 0);
    store.close(); store = new SqliteStore(dbFile);
    assert.equal(store.loadState().qaBugs.find(row => row.id === bug.id).reopenCount, 1);
    assert.equal(store.loadState().contentCenter.find(row => row.id === content.id).contentBody, 'New draft');
    assert.equal(store.loadState().teams.length, 0);
  });
});
